-- V1: Initial schema for Citizens and Permit Applications
CREATE TABLE citizens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    citizen_pin VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    phone_number VARCHAR(30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_citizen_pin ON citizens(citizen_pin);

CREATE TABLE permit_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(30) NOT NULL UNIQUE,
    permit_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    decision_remarks VARCHAR(500),
    citizen_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_permits_citizen FOREIGN KEY (citizen_id) REFERENCES citizens(id) ON DELETE CASCADE
);

CREATE INDEX idx_tracking_number ON permit_applications(tracking_number);
CREATE INDEX idx_permit_status ON permit_applications(status);